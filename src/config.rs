//! Writing the generated ssh_config, the `.pub` files, and the Include line.

use std::collections::HashSet;
use std::fmt::Write as _;
use std::fs;
use std::io::{self, Write as _};
use std::path::{Path, PathBuf};

use crate::agent::Key;
use crate::platform::{clean_abs, format_include, to_slash};
use crate::target::{parse_target, sanitize, skip_key};

/// Marker file that proves bwsshd owns the key directory.
pub const KEYDIR_MARKER: &str = ".bwsshd";

type Result<T> = std::result::Result<T, String>;

/// Writes one `.pub` per key and a `Host` block per key whose Bitwarden name
/// carries a hostname. Keys with no hostname are written and listed as
/// comments for a manual Host block. Stale `.pub` files are removed.
pub fn generate(keys: &[Key], out: &Path, keydir: &Path, sock: &str) -> Result<()> {
    ensure_keydir(keydir)?;

    // Stable order so "first key wins" on a duplicate host is deterministic.
    let mut keys: Vec<&Key> = keys.iter().collect();
    keys.sort_by_cached_key(|k| k.fingerprint_sha256());

    let mut cfg = String::from("# Generated by bwsshd. Do not edit; changes are overwritten.\n\n");
    let mut written: HashSet<String> = HashSet::new();
    let mut seen_hosts: HashSet<String> = HashSet::new();
    let mut unmapped = Vec::new();
    let mut hosts = 0;

    for k in keys {
        if skip_key(&k.comment) {
            continue;
        }

        let target = parse_target(&k.comment);
        if let Some(t) = &target
            && seen_hosts.contains(&t.host)
        {
            info!(
                "multiple keys map to host {}; keeping the first, ignoring {:?}",
                t.host, k.comment
            );
            continue;
        }

        let base = [
            target.as_ref().map(|t| sanitize(&t.host)),
            Some(sanitize(&k.comment)),
        ]
        .into_iter()
        .flatten()
        .find(|s| !s.is_empty())
        .unwrap_or_else(|| "key".into());

        // Never clobber another key's .pub when filenames collide.
        let mut file = format!("{base}.pub");
        let mut i = 2;
        while written.contains(&file) {
            file = format!("{base}-{i}.pub");
            i += 1;
        }

        let pub_path = keydir.join(&file);
        write_file(&pub_path, format!("{}\n", k.to_openssh()).as_bytes())?;
        written.insert(file);

        match target {
            Some(t) => {
                hosts += 1;
                let _ = writeln!(cfg, "Host {}\n    HostName {}", t.host, t.hostname);
                if let Some(u) = &t.user {
                    let _ = writeln!(cfg, "    User {u}");
                }
                if let Some(p) = &t.port {
                    let _ = writeln!(cfg, "    Port {p}");
                }
                let _ = writeln!(
                    cfg,
                    "    IdentityAgent {}\n    IdentityFile {}\n    IdentitiesOnly yes\n",
                    to_slash(sock),
                    to_slash(&pub_path)
                );
                seen_hosts.insert(t.host);
            }
            None => unmapped.push(format!("{:?} -> {}", k.comment, pub_path.display())),
        }
    }

    if !unmapped.is_empty() {
        cfg.push_str("# Keys with no hostname in their Bitwarden name. Add a manual Host\n");
        cfg.push_str("# block referencing the .pub below:\n");
        for u in &unmapped {
            let _ = writeln!(cfg, "#   {u}");
        }
    }

    write_file(out, cfg.as_bytes())?;

    // Drop .pub files for keys no longer in the agent (the marker isn't *.pub).
    if let Ok(entries) = fs::read_dir(keydir) {
        for e in entries.flatten() {
            let name = e.file_name().to_string_lossy().into_owned();
            if name.ends_with(".pub") && !written.contains(&name) {
                let _ = fs::remove_file(e.path());
            }
        }
    }

    info!(
        "wrote {}: {hosts} host(s), {} key(s) without a hostname",
        out.display(),
        unmapped.len()
    );
    Ok(())
}

/// Run when the agent is gone: empty the config so SSH's Include never breaks
/// on a missing file, and remove the whole keydir, but only if we own it.
pub fn clean(out: &Path, keydir: &Path) -> Result<()> {
    write_file(
        out,
        b"# bwsshd: Bitwarden SSH agent socket absent, no keys offered.\n",
    )?;
    // Only wipe a real directory we own (marker present), never through a symlink.
    let is_real_dir = fs::symlink_metadata(keydir).is_ok_and(|m| m.is_dir());
    if is_real_dir && keydir.join(KEYDIR_MARKER).exists() {
        fs::remove_dir_all(keydir).map_err(|e| format!("remove {}: {e}", keydir.display()))?;
    }
    info!("agent socket absent, cleared {}", out.display());
    Ok(())
}

/// Creates `dir` and marks it as managed by bwsshd so [`clean`] can safely wipe
/// the whole directory. Refuses to claim a directory that already holds
/// unrelated files (e.g. `--keydir ~/.ssh`), which is what prevents deleting
/// the user's own keys.
pub fn ensure_keydir(dir: &Path) -> Result<()> {
    // A symlinked keydir would make the later remove_dir_all hit the link target.
    if fs::symlink_metadata(dir).is_ok_and(|m| m.file_type().is_symlink()) {
        return Err(format!(
            "keydir {} is a symlink; refusing to use it",
            dir.display()
        ));
    }
    create_private_dir(dir)?;
    let marker = dir.join(KEYDIR_MARKER);
    if marker.exists() {
        return Ok(());
    }
    let mut entries = fs::read_dir(dir).map_err(|e| format!("read {}: {e}", dir.display()))?;
    if entries.next().is_some() {
        return Err(format!(
            "keydir {} is not empty and not managed by bwsshd; refusing to use it",
            dir.display()
        ));
    }
    write_file(
        &marker,
        b"Managed by bwsshd; this directory is removed when the agent socket is gone.\n",
    )
}

/// Prepends an `Include` of the generated file to `ssh_config` so plain
/// `ssh host` picks up the per-host blocks. It goes at the top because SSH is
/// first-match-wins for IdentityFile/User/etc. It is idempotent.
pub fn ensure_include(ssh_config: &Path, out: &Path) -> Result<()> {
    let want = clean_abs(out).map_err(|e| format!("{}: {e}", out.display()))?;
    let dir = match ssh_config.parent() {
        Some(p) if !p.as_os_str().is_empty() => p.to_path_buf(),
        _ => PathBuf::from("."),
    };
    let data = match fs::read_to_string(ssh_config) {
        Ok(d) => d,
        Err(e) if e.kind() == io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(format!("read {}: {e}", ssh_config.display())),
    };

    let already = data.lines().any(|line| {
        let mut f = line.split_whitespace();
        f.next().is_some_and(|kw| kw.eq_ignore_ascii_case("Include"))
            // Include can list several files; resolve each the way OpenSSH
            // would and compare absolute paths, so a same-basename include of a
            // different file isn't a false match.
            && f.any(|inc| include_resolves(&dir, inc, &want))
    });
    if already {
        return Ok(());
    }

    create_private_dir(&dir)?;
    let line = format_include(&dir, out);
    let body = format!("# Added by bwsshd\nInclude {line}\n\n{data}");
    info!("added Include {line} to {}", ssh_config.display());
    write_file(ssh_config, body.as_bytes())
}

/// Reports whether an Include token points at `want` (an absolute path). A
/// relative token is resolved against the config directory, like OpenSSH does.
fn include_resolves(dir: &Path, inc: &str, want: &Path) -> bool {
    let p = Path::new(inc);
    let p = if p.is_absolute() {
        p.to_path_buf()
    } else {
        dir.join(p)
    };
    clean_abs(&p).is_ok_and(|abs| abs == want)
}

/// Writes `data` atomically: a temp file in the same directory, made private
/// before the rename, so the visible file is never partially written nor
/// briefly world-readable, and a crash never truncates an existing file (for
/// example ~/.ssh/config).
pub fn write_file(path: &Path, data: &[u8]) -> Result<()> {
    let err = |e: io::Error| format!("write {}: {e}", path.display());
    let dir = match path.parent() {
        Some(p) if !p.as_os_str().is_empty() => p,
        _ => Path::new("."),
    };
    let mut tmp = tempfile::Builder::new()
        .prefix(".bwsshd-")
        .tempfile_in(dir)
        .map_err(err)?;
    tmp.write_all(data).map_err(err)?;
    tmp.as_file().sync_all().map_err(err)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        fs::set_permissions(tmp.path(), fs::Permissions::from_mode(0o600)).map_err(err)?;
    }
    tmp.persist(path).map_err(|e| err(e.error))?;
    Ok(())
}

/// `mkdir -p` with mode 0700 on unix.
pub fn create_private_dir(dir: &Path) -> Result<()> {
    let mut b = fs::DirBuilder::new();
    b.recursive(true);
    #[cfg(unix)]
    {
        use std::os::unix::fs::DirBuilderExt;
        b.mode(0o700);
    }
    b.create(dir)
        .map_err(|e| format!("mkdir {}: {e}", dir.display()))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::agent::tests::key;
    use tempfile::TempDir;

    fn read(p: &Path) -> String {
        fs::read_to_string(p).unwrap()
    }

    fn pubs(dir: &Path) -> Vec<String> {
        let mut v: Vec<String> = fs::read_dir(dir)
            .unwrap()
            .flatten()
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .filter(|n| n.ends_with(".pub"))
            .collect();
        v.sort();
        v
    }

    #[test]
    fn generate_host_block() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(&[key("debian@host.fr:2222")], &out, &keydir, "/sock").unwrap();
        let cfg = read(&out);
        for want in [
            "Host host.fr",
            "HostName host.fr",
            "User debian",
            "Port 2222",
            "IdentitiesOnly yes",
        ] {
            assert!(cfg.contains(want), "config missing {want:?}:\n{cfg}");
        }
        assert!(keydir.join("host.fr.pub").exists());
        assert!(keydir.join(KEYDIR_MARKER).exists());
    }

    #[test]
    fn generate_alias_block() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(
            &[key("debian@(vps1,[2001:db8::10]):23487")],
            &out,
            &keydir,
            "/sock",
        )
        .unwrap();
        let cfg = read(&out);
        for want in [
            "Host vps1\n",
            "HostName 2001:db8::10\n",
            "User debian",
            "Port 23487",
        ] {
            assert!(cfg.contains(want), "config missing {want:?}:\n{cfg}");
        }
        // The .pub is named after the alias, the name you type after `ssh`.
        assert_eq!(pubs(&keydir), ["vps1.pub"]);
    }

    // Issue #3: two keys on the same host -> first wins, one block, one .pub.
    #[test]
    fn generate_duplicate_host() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(
            &[key("host.fr"), key("root@host.fr")],
            &out,
            &keydir,
            "/sock",
        )
        .unwrap();
        assert_eq!(read(&out).matches("Host host.fr\n").count(), 1);
        assert_eq!(pubs(&keydir).len(), 1);
    }

    // Issue #3: distinct unmapped keys whose names collide get a -2 suffix.
    #[test]
    fn generate_filename_collision() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(
            &[key("shared one"), key("shared/one")],
            &out,
            &keydir,
            "/sock",
        )
        .unwrap();
        assert_eq!(pubs(&keydir), ["shared_one-2.pub", "shared_one.pub"]);
    }

    // Issue #3: a hostname-less key is written and listed for a manual Host block.
    #[test]
    fn generate_unmapped() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(&[key("ansible")], &out, &keydir, "/sock").unwrap();
        let cfg = read(&out);
        assert!(
            cfg.contains("manual Host") && cfg.contains("\"ansible\""),
            "{cfg}"
        );
        assert_eq!(pubs(&keydir), ["ansible.pub"]);
    }

    #[test]
    fn generate_skips_and_prunes_stale() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(&[key("old.example.com")], &out, &keydir, "/sock").unwrap();
        generate(
            &[key("new.example.com"), key("hidden.example.com [nobwsshd]")],
            &out,
            &keydir,
            "/sock",
        )
        .unwrap();
        assert_eq!(pubs(&keydir), ["new.example.com.pub"]);
        assert!(!read(&out).contains("hidden.example.com"));
    }

    // The generated block must use forward slashes: OpenSSH on Windows accepts
    // //./pipe/... and C:/... but treats backslashes as escapes.
    #[test]
    #[cfg(windows)]
    fn generate_forward_slashes_windows() {
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(
            &[key("debian@host.fr")],
            &out,
            &keydir,
            crate::platform::OPENSSH_AGENT_PIPE,
        )
        .unwrap();
        let cfg = read(&out);
        assert!(
            cfg.contains("IdentityAgent //./pipe/openssh-ssh-agent"),
            "{cfg}"
        );
        for l in cfg.lines() {
            if l.trim_start().starts_with("Identity") {
                assert!(!l.contains('\\'), "backslash in {l:?}");
            }
        }
    }

    #[test]
    #[cfg(unix)]
    fn generate_private_permissions() {
        use std::os::unix::fs::PermissionsExt;
        let dir = TempDir::new().unwrap();
        let (out, keydir) = (dir.path().join("config.bw"), dir.path().join("keys"));
        generate(&[key("host.fr")], &out, &keydir, "/sock").unwrap();
        let mode = |p: &Path| fs::metadata(p).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode(&out), 0o600);
        assert_eq!(mode(&keydir.join("host.fr.pub")), 0o600);
        assert_eq!(mode(&keydir), 0o700);
    }

    // Issue #3: ensure_keydir refuses a non-empty unmanaged dir and a symlink.
    #[test]
    fn ensure_keydir_guards() {
        let dir = TempDir::new().unwrap();
        let used = dir.path().join("keys");
        fs::create_dir_all(&used).unwrap();
        fs::write(used.join("id_ed25519"), "x").unwrap();
        assert!(ensure_keydir(&used).is_err());

        let target = TempDir::new().unwrap();
        let link = dir.path().join("link");
        #[cfg(unix)]
        let made = std::os::unix::fs::symlink(target.path(), &link);
        #[cfg(windows)]
        let made = std::os::windows::fs::symlink_dir(target.path(), &link);
        if made.is_err() {
            return; // Windows without Developer Mode cannot create symlinks
        }
        assert!(ensure_keydir(&link).is_err());
    }

    // Issue #3: clean removes a marked keydir but spares an unmanaged one.
    #[test]
    fn clean_keydir_guard() {
        let dir = TempDir::new().unwrap();
        let out = dir.path().join("config.bw");

        let owned = dir.path().join("owned");
        fs::create_dir_all(&owned).unwrap();
        fs::write(owned.join(KEYDIR_MARKER), "").unwrap();
        clean(&out, &owned).unwrap();
        assert!(!owned.exists(), "clean did not remove a marked keydir");
        assert!(read(&out).contains("socket absent"));

        let foreign = dir.path().join("foreign");
        fs::create_dir_all(&foreign).unwrap();
        fs::write(foreign.join("id_ed25519"), "x").unwrap();
        clean(&out, &foreign).unwrap();
        assert!(
            foreign.join("id_ed25519").exists(),
            "clean removed an unmanaged keydir"
        );
    }

    // Issue #3 + #5: ensure_include prepends once, is idempotent, and does not
    // false-match a different file sharing the same basename.
    #[test]
    fn ensure_include_idempotent() {
        let dir = TempDir::new().unwrap();
        let cfg = dir.path().join("config");
        let out = dir.path().join("config.automatic.bw");

        ensure_include(&cfg, &out).unwrap();
        let first = read(&cfg);
        assert_eq!(first.matches("Include ").count(), 1, "{first}");
        ensure_include(&cfg, &out).unwrap();
        assert_eq!(read(&cfg), first, "not idempotent");

        let dir2 = TempDir::new().unwrap();
        let cfg2 = dir2.path().join("config");
        fs::write(&cfg2, "Include /somewhere/else/config.automatic.bw\n").unwrap();
        ensure_include(&cfg2, &out).unwrap();
        assert_eq!(read(&cfg2).matches("Include ").count(), 2);
        ensure_include(&cfg2, &out).unwrap();
        assert_eq!(read(&cfg2).matches("Include ").count(), 2);
    }

    #[test]
    fn ensure_include_accepts_existing_relative() {
        let dir = TempDir::new().unwrap();
        let cfg = dir.path().join("config");
        let out = dir.path().join("config.automatic.bw");
        fs::write(&cfg, "Host *\n  include ./config.automatic.bw other\n").unwrap();
        ensure_include(&cfg, &out).unwrap();
        assert!(!read(&cfg).contains("Added by bwsshd"));
    }
}

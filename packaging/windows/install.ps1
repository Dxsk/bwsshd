<#
.SYNOPSIS
    Install bwsshd as a per-user background agent on Windows.

.DESCRIPTION
    Registers a Scheduled Task that runs `bwsshd -watch` at logon, under your own
    account, in your interactive session. This is the Windows equivalent of the
    Linux `systemctl --user` service: it must run as you (not as a system
    service), because the Bitwarden SSH agent pipe and your ~/.ssh are per-user.

    The watcher runs hidden (no console window) via a small wscript launcher that
    waits on the process, so the task tracks the daemon and restarts it on crash.
    No administrator rights required.

.PARAMETER Bin
    Path to bwsshd.exe. Auto-detected from this script's folder or ..\..\dist if
    omitted.

.PARAMETER Interval
    Poll interval passed to -watch (default 10s).

.PARAMETER TaskName
    Scheduled Task name (default "bwsshd"). Override to test without touching a
    real install.

.PARAMETER Out, Keydir, SshConfig, LogFile
    Advanced/testing overrides for the matching bwsshd flags and the log path.

.EXAMPLE
    powershell -ExecutionPolicy Bypass -File .\install.ps1
#>
[CmdletBinding()]
param(
    [string]$Bin,
    [string]$Interval = "10s",
    [string]$TaskName = "bwsshd",
    [string]$Out,
    [string]$Keydir,
    [string]$SshConfig,
    [string]$LogFile
)

$ErrorActionPreference = "Stop"

$InstallDir = Join-Path $env:LOCALAPPDATA "Programs\bwsshd"
if (-not $LogFile) { $LogFile = Join-Path $env:LOCALAPPDATA "bwsshd\bwsshd.log" }

# 1. Locate the binary.
if (-not $Bin) {
    $here = Split-Path -Parent $MyInvocation.MyCommand.Path
    foreach ($c in @(
            (Join-Path $here "bwsshd.exe"),          # release zip: script sits next to the exe
            (Join-Path $here "..\..\dist\bwsshd.exe"), # repo: after `make build`
            (Join-Path $here "..\..\bwsshd.exe"))) {
        if (Test-Path $c) { $Bin = (Resolve-Path $c).Path; break }
    }
}
if (-not $Bin) {
    $g = Get-Command bwsshd.exe -ErrorAction SilentlyContinue
    if ($g) { $Bin = $g.Source }
}
if (-not $Bin -or -not (Test-Path $Bin)) {
    throw "bwsshd.exe not found. Build it (make build) or pass -Bin <path>."
}

# 2. Install the binary and create the log directory.
New-Item -ItemType Directory -Force -Path $InstallDir, (Split-Path -Parent $LogFile) | Out-Null
$TargetBin = Join-Path $InstallDir "bwsshd.exe"
Copy-Item -Path $Bin -Destination $TargetBin -Force

# 3. Build the command line and a hidden wscript launcher.
#    wscript.exe has no console of its own; Run(cmd, 0, True) starts bwsshd with a
#    hidden window (0) and waits (True) so the task keeps tracking it. Quitting
#    with bwsshd's exit code lets the task's restart-on-failure kick in.
$cmd = '"' + $TargetBin + '" -watch -interval ' + $Interval + ' -logfile "' + $LogFile + '"'
if ($Out) { $cmd += ' -out "' + $Out + '"' }
if ($Keydir) { $cmd += ' -keydir "' + $Keydir + '"' }
if ($SshConfig) { $cmd += ' -ssh-config "' + $SshConfig + '"' }

$Vbs = Join-Path $InstallDir "bwsshd-launch.vbs"
$vbsCmd = $cmd -replace '"', '""'   # escape quotes for a VBScript string literal
@"
' Generated by bwsshd install.ps1 -- do not edit.
' Launches the watcher hidden and waits, so the Scheduled Task tracks the daemon.
WScript.Quit CreateObject("WScript.Shell").Run("$vbsCmd", 0, True)
"@ | Set-Content -Path $Vbs -Encoding Ascii

# 4. Register the Scheduled Task: at logon, your account, interactive (in-session),
#    unelevated, no time limit, restart a few times on failure.
$action = New-ScheduledTaskAction -Execute "wscript.exe" -Argument ('"' + $Vbs + '"')
$trigger = New-ScheduledTaskTrigger -AtLogOn -User "$env:USERDOMAIN\$env:USERNAME"
$principal = New-ScheduledTaskPrincipal -UserId "$env:USERDOMAIN\$env:USERNAME" -LogonType Interactive -RunLevel Limited
$settings = New-ScheduledTaskSettingsSet `
    -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable `
    -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1) `
    -ExecutionTimeLimit ([TimeSpan]::Zero)

Register-ScheduledTask -TaskName $TaskName -Action $action -Trigger $trigger `
    -Principal $principal -Settings $settings -Force | Out-Null

Start-ScheduledTask -TaskName $TaskName

Write-Host "bwsshd installed and started."
Write-Host "  binary : $TargetBin"
Write-Host "  logs   : $LogFile"
Write-Host "  task   : $TaskName  (Task Scheduler > at logon)"
Write-Host ""
Write-Host "follow logs:  Get-Content -Wait `"$LogFile`""
Write-Host "uninstall:    powershell -ExecutionPolicy Bypass -File .\uninstall.ps1"
